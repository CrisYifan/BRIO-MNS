def 计算共享归一化基准(参数, 初始种群, 距离矩阵):
    """从共享初始种群计算一次固定基准，不使用任何算法的未来结果。"""
    原始参数 = copy.deepcopy(参数)
    原始参数["启用归一化复合目标"] = False
    工具 = 工具类(原始参数)
    指标列表 = [工具.路径指标计算(个体, 距离矩阵) for 个体 in 初始种群]

    # 采用共享初始种群的中位数降低极端随机个体影响；同一配对中的算法共享该常数。
    return {
        "路径总长": statistics.median(指标[2] for 指标 in 指标列表),
        "路径均衡": statistics.median(指标[3] for 指标 in 指标列表),
        "负载均衡": statistics.median(指标[4] for 指标 in 指标列表),
    }


class 目标一致SVGA求解器(SVGA求解器):
    """以真实复合目标增益筛选邻域的实验求解器。"""

    def __init__(self, *args, 启用路径内优化=False, 启用路径保持交叉=False, **kwargs):
        super().__init__(*args, **kwargs)
        self.启用路径内优化 = 启用路径内优化
        self.启用路径保持交叉 = 启用路径保持交叉
        self._最近客户 = self._创建最近客户表()

    def _创建最近客户表(self):
        最近客户 = {}
        for 客户 in range(1, self.客户数量 + 1):
            最近客户[客户] = sorted(
                (其他 for 其他 in range(1, self.客户数量 + 1) if 其他 != 客户),
                key=lambda 其他: self.距离矩阵[客户][其他],
            )
        return 最近客户

    def _位置负担(self, 个体序列, 位置):
        """使用与距离及剩余载荷相关的廉价代理筛选少量重点客户。"""
        容量 = self.参数["车辆容量"]
        块起点 = (位置 // 容量) * 容量
        块终点 = min(块起点 + 容量, len(个体序列))
        块内位置 = 位置 - 块起点
        当前客户 = 个体序列[位置]
        前客户 = 0 if 位置 == 块起点 else 个体序列[位置 - 1]
        后客户 = 0 if 位置 == 块终点 - 1 else 个体序列[位置 + 1]
        入边载荷 = (容量 - 块内位置) / 容量
        出边载荷 = max(容量 - 块内位置 - 1, 0) / 容量
        return (self.距离矩阵[前客户][当前客户] * (1.0 + 入边载荷) +
                self.距离矩阵[当前客户][后客户] * (1.0 + 出边载荷))

    def _生成目标一致候选(self, 个体序列):
        """生成少量结构化候选；最终排序只依据真实复合目标改善。"""
        容量 = self.参数["车辆容量"]
        客户到位置 = {客户: 位置 for 位置, 客户 in enumerate(个体序列)}
        节点数 = min(self.参数.get("目标一致候选节点数", 8), len(个体序列))
        重点位置 = sorted(
            range(len(个体序列)),
            key=lambda 位置: self._位置负担(个体序列, 位置),
            reverse=True,
        )[:节点数]

        候选 = []
        已见 = set()
        近邻数 = self.参数.get("每节点近邻伙伴数", 4)
        随机数 = self.参数.get("每节点随机伙伴数", 2)
        for 位置 in 重点位置:
            客户 = 个体序列[位置]
            当前块 = 位置 // 容量
            伙伴位置 = []
            for 其他客户 in self._最近客户[客户]:
                其他位置 = 客户到位置[其他客户]
                if 其他位置 // 容量 != 当前块:
                    伙伴位置.append(其他位置)
                if len(伙伴位置) >= 近邻数:
                    break

            其他块位置 = [
                j for j in range(len(个体序列))
                if j // 容量 != 当前块 and j not in 伙伴位置
            ]
            if 其他块位置:
                伙伴位置.extend(random.sample(其他块位置, min(随机数, len(其他块位置))))

            for 其他位置 in 伙伴位置:
                键 = ("swap",) + tuple(sorted((位置, 其他位置)))
                if 键 in 已见:
                    continue
                已见.add(键)
                新序列 = 个体序列[:]
                新序列[位置], 新序列[其他位置] = 新序列[其他位置], 新序列[位置]
                候选.append(新序列)

        if self.启用路径内优化:
            路径数 = len(个体序列) // 容量
            重点路径数 = min(self.参数.get("重点路径数量", 4), 路径数)
            路径索引 = sorted(
                range(路径数),
                key=lambda r: sum(
                    self._位置负担(个体序列, r * 容量 + j) for j in range(容量)
                ),
                reverse=True,
            )[:重点路径数]
            for 路径 in 路径索引:
                起点 = 路径 * 容量
                终点 = 起点 + 容量
                for 左 in range(容量 - 1):
                    for 右 in range(左 + 1, 容量):
                        新序列 = 个体序列[:]
                        新序列[起点 + 左:起点 + 右 + 1] = reversed(
                            新序列[起点 + 左:起点 + 右 + 1]
                        )
                        键 = tuple(新序列)
                        if 键 not in 已见:
                            已见.add(键)
                            候选.append(新序列)
        return 候选

    def _目标一致局部搜索(self, 个体序列):
        当前序列 = 个体序列[:]
        当前适应度 = self.工具.适应度计算(当前序列, self.距离矩阵)
        for _ in range(self.参数.get("局部搜索步数", 1)):
            最优序列 = 当前序列
            最优适应度 = 当前适应度
            for 候选序列 in self._生成目标一致候选(当前序列):
                候选适应度 = self.工具.适应度计算(候选序列, self.距离矩阵)
                if 候选适应度 < 最优适应度 - 1e-12:
                    最优适应度 = 候选适应度
                    最优序列 = 候选序列
            if 最优序列 is 当前序列:
                break
            当前序列, 当前适应度 = 最优序列, 最优适应度
        # 候选节点和伙伴都由真实归一化复合目标增益验证，修复旧评分与真实改善近零相关的问题。
        return 当前序列

    def _探索阶段变异(self, 个体序列):
        if random.random() <= self.参数.get("shapley应用概率", 0.4):
            return self._目标一致局部搜索(个体序列)
        i, j = random.sample(range(len(个体序列)), 2)
        新序列 = 个体序列[:]
        新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        return 新序列

    def _收敛阶段变异(self, 个体序列):
        return self._目标一致局部搜索(个体序列)

    def _路径距离(self, 路径):
        return (self.距离矩阵[0][路径[0]] +
                sum(self.距离矩阵[a][b] for a, b in zip(路径, 路径[1:])) +
                self.距离矩阵[路径[-1]][0])

    def _优化短路径顺序(self, 路径):
        return list(min(itertools.permutations(路径), key=self._路径距离))

    def _单向路径保持交叉(self, 捐赠父代, 基础父代):
        容量 = self.参数["车辆容量"]
        捐赠路径 = [捐赠父代[i:i + 容量] for i in range(0, len(捐赠父代), 容量)]
        基础路径 = [基础父代[i:i + 容量] for i in range(0, len(基础父代), 容量)]
        继承数 = min(self.参数.get("路径交叉继承数量", 2), len(捐赠路径))

        # 优先继承父代中的完整短路径，避免普通OX在任意基因位置切断车辆路径块。
        优质路径池 = sorted(捐赠路径, key=self._路径距离)[:max(继承数 * 3, 继承数)]
        继承路径 = [list(路径) for 路径 in random.sample(优质路径池, 继承数)]
        已用客户 = {客户 for 路径 in 继承路径 for 客户 in 路径}

        完整基础路径 = []
        待重组客户 = []
        for 路径 in 基础路径:
            剩余 = [客户 for 客户 in 路径 if 客户 not in 已用客户]
            if len(剩余) == 容量:
                完整基础路径.append(剩余)
            else:
                待重组客户.extend(剩余)

        重组路径 = []
        while 待重组客户:
            起点 = 待重组客户.pop(0)
            当前路径 = [起点]
            while len(当前路径) < 容量:
                下一个 = min(待重组客户, key=lambda 客户: self.距离矩阵[当前路径[-1]][客户])
                待重组客户.remove(下一个)
                当前路径.append(下一个)
            重组路径.append(self._优化短路径顺序(当前路径))

        子代路径 = 继承路径 + 完整基础路径 + 重组路径
        random.shuffle(子代路径)
        子代 = [客户 for 路径 in 子代路径 for 客户 in 路径]
        if len(子代) != len(捐赠父代) or set(子代) != set(捐赠父代):
            raise AssertionError("路径保持交叉生成了非法排列")
        return 子代

    def _选择交叉(self, 种群, 精英数量, 父代数量):
        if not self.启用路径保持交叉:
            return super()._选择交叉(种群, 精英数量, 父代数量)

        排序种群 = sorted(
            ((个体, self.工具.适应度计算(个体, self.距离矩阵)) for 个体 in 种群),
            key=lambda 项: 项[1],
        )
        新种群 = [个体[:] for 个体, _ in 排序种群[:精英数量]]
        父代池 = [个体 for 个体, _ in 排序种群[:min(父代数量, len(排序种群))]]
        while len(新种群) < len(种群):
            父代1, 父代2 = random.sample(父代池, 2)
            新种群.append(self._单向路径保持交叉(父代1, 父代2))
            if len(新种群) < len(种群):
                新种群.append(self._单向路径保持交叉(父代2, 父代1))
        return 新种群


class 预算混合求解器(GA求解器):
    """先遗传搜索、再在同一总评估预算内进行自适应局部精修。"""

    def __init__(
        self, *args, 启用贡献引导=False, 候选批量大小=1,
        自适应算子=False, 统一六算子=False,
        禁用负担引导=False, 匹配随机负担=False,
        复合负担代理=False, 引导使用概率=1.0, **kwargs
    ):
        super().__init__(*args, **kwargs)
        self.启用贡献引导 = 启用贡献引导
        self.候选批量大小 = max(int(候选批量大小), 1)
        self.自适应算子 = 自适应算子
        # 增加固定均匀概率的六邻域版本，用作检验“自适应权重”贡献的受控基线。
        self.统一六算子 = 统一六算子
        # 发布级消融分别检验“整个第六算子”和“负担排序本身”的贡献。
        self.禁用负担引导 = 禁用负担引导
        self.匹配随机负担 = 匹配随机负担
        # 旧负担算子用h_i定位后只按距离筛选候选，与最终复合目标F不完全一致；
        # 新变体可用受影响路线的充分统计量直接比较D、BD和BL的归一化复合增量。
        self.复合负担代理 = 复合负担代理
        # Matched-Random16显著优于始终选择高负担位置，允许在负担排序和均匀目标之间受控混合。
        self.引导使用概率 = min(max(float(引导使用概率), 0.0), 1.0)
        self._最近客户 = self._创建最近客户表()

    def _创建最近客户表(self):
        return {
            客户: sorted(
                (其他 for 其他 in range(1, self.客户数量 + 1) if 其他 != 客户),
                key=lambda 其他: self.距离矩阵[客户][其他],
            )
            for 客户 in range(1, self.客户数量 + 1)
        }

    def _路径距离(self, 路径):
        return (self.距离矩阵[0][路径[0]] +
                sum(self.距离矩阵[a][b] for a, b in zip(路径, 路径[1:])) +
                self.距离矩阵[路径[-1]][0])

    def _路径充分统计(self, 路径):
        """返回可增量恢复D、BD和BL的一条路线充分统计量。"""
        容量 = len(路径)
        边长 = [self.距离矩阵[0][路径[0]]]
        边长.extend(self.距离矩阵[a][b] for a, b in zip(路径, 路径[1:]))
        边长.append(self.距离矩阵[路径[-1]][0])
        载荷率 = [(容量 - j) / 容量 for j in range(容量)] + [0.0]
        载荷距离 = [载荷 * 距离 for 载荷, 距离 in zip(载荷率, 边长)]
        return (
            sum(边长),
            sum(距离 * 距离 for 距离 in 边长),
            sum(载荷距离),
            sum(值 * 值 for 值 in 载荷距离),
        )

    def _全局充分统计(self, 个体序列):
        容量 = self.参数["车辆容量"]
        路线统计 = [
            self._路径充分统计(个体序列[起点:起点 + 容量])
            for 起点 in range(0, len(个体序列), 容量)
        ]
        return tuple(sum(统计[列] for 统计 in 路线统计) for 列 in range(4))

    def _统计复合代价(self, 统计):
        """由全局充分统计量计算与正式目标完全同向的无副作用代理。"""
        距离和, 距离平方和, 载荷距离和, 载荷距离平方和 = 统计
        容量 = self.参数["车辆容量"]
        边数 = (len(self.初始种群[0]) // 容量) * (容量 + 1)
        路径均衡 = max(距离平方和 / 边数 - (距离和 / 边数) ** 2, 0.0)
        负载均衡 = max(
            载荷距离平方和 / 边数 - (载荷距离和 / 边数) ** 2,
            0.0,
        )
        if self.参数.get("启用归一化复合目标", False):
            基准 = self.参数["复合目标归一化基准"]
            距离和 /= max(float(基准["路径总长"]), 1e-12)
            路径均衡 /= max(float(基准["路径均衡"]), 1e-12)
            负载均衡 /= max(float(基准["负载均衡"]), 1e-12)
        return (
            self.参数["路径长系数"] * 距离和
            + self.参数["路径均衡系数"] * 路径均衡
            + self.参数["负载均衡系数"] * 负载均衡
        )

    def _替换路线复合代理(self, 全局统计, 原路线列表, 新路线列表):
        新统计 = list(全局统计)
        for 原路线 in 原路线列表:
            原统计 = self._路径充分统计(原路线)
            for 列 in range(4):
                新统计[列] -= 原统计[列]
        for 新路线 in 新路线列表:
            候选统计 = self._路径充分统计(新路线)
            for 列 in range(4):
                新统计[列] += 候选统计[列]
        return self._统计复合代价(tuple(新统计))

    def _本次使用负担排序(self):
        if self.匹配随机负担 or self.引导使用概率 <= 0.0:
            return False
        if self.引导使用概率 >= 1.0:
            return True
        return random.random() < self.引导使用概率

    def _位置负担(self, 个体序列, 位置):
        容量 = self.参数["车辆容量"]
        块起点 = (位置 // 容量) * 容量
        块终点 = 块起点 + 容量
        块内位置 = 位置 - 块起点
        客户 = 个体序列[位置]
        前客户 = 0 if 位置 == 块起点 else 个体序列[位置 - 1]
        后客户 = 0 if 位置 == 块终点 - 1 else 个体序列[位置 + 1]
        入载荷 = (容量 - 块内位置) / 容量
        出载荷 = max(容量 - 块内位置 - 1, 0) / 容量
        return (self.距离矩阵[前客户][客户] * (1.0 + 入载荷) +
                self.距离矩阵[客户][后客户] * (1.0 + 出载荷))

    def _随机邻域(self, 个体序列):
        新序列 = 个体序列[:]
        if random.random() < 0.25:
            容量 = self.参数["车辆容量"]
            路径 = random.randrange(len(个体序列) // 容量)
            左, 右 = sorted(random.sample(range(容量), 2))
            起点 = 路径 * 容量
            新序列[起点 + 左:起点 + 右 + 1] = reversed(新序列[起点 + 左:起点 + 右 + 1])
        else:
            i, j = random.sample(range(len(个体序列)), 2)
            新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        return 新序列

    def _按算子生成邻域(self, 个体序列, 算子):
        容量 = self.参数["车辆容量"]
        新序列 = 个体序列[:]
        if 算子 == "任意交换":
            i, j = random.sample(range(len(个体序列)), 2)
            新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        elif 算子 == "跨路径交换":
            i = random.randrange(len(个体序列))
            候选 = [j for j in range(len(个体序列)) if j // 容量 != i // 容量]
            j = random.choice(候选)
            新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        elif 算子 == "路径内反转":
            路径 = random.randrange(len(个体序列) // 容量)
            左, 右 = sorted(random.sample(range(容量), 2))
            起点 = 路径 * 容量
            新序列[起点 + 左:起点 + 右 + 1] = reversed(新序列[起点 + 左:起点 + 右 + 1])
        elif 算子 == "路径内重排":
            路径 = random.randrange(len(个体序列) // 容量)
            起点 = 路径 * 容量
            原路径 = 新序列[起点:起点 + 容量]
            新路径 = random.sample(原路径, len(原路径))
            新序列[起点:起点 + 容量] = 新路径
        elif 算子 == "双客户段交换":
            路径1, 路径2 = random.sample(range(len(个体序列) // 容量), 2)
            起始1 = random.randrange(容量 - 1)
            起始2 = random.randrange(容量 - 1)
            a = 路径1 * 容量 + 起始1
            b = 路径2 * 容量 + 起始2
            片段1 = 新序列[a:a + 2]
            片段2 = 新序列[b:b + 2]
            新序列[a:a + 2], 新序列[b:b + 2] = 片段2, 片段1
        elif 算子 == "负担引导":
            return self._引导邻域(个体序列)
        else:
            raise ValueError(f"未知邻域算子: {算子}")
        return 新序列

    @staticmethod
    def _按权重选择算子(算子权重):
        总权重 = sum(算子权重.values())
        阈值 = random.random() * 总权重
        累计 = 0.0
        for 算子, 权重 in 算子权重.items():
            累计 += 权重
            if 累计 >= 阈值:
                return 算子
        return next(reversed(算子权重))

    def _引导邻域(self, 个体序列):
        容量 = self.参数["车辆容量"]
        if random.random() < 0.30:
            # 容量为4时可零目标评估地枚举24种顺序，以距离代理选择路径内候选，
            # 随后仍用真实复合目标决定是否接受，减少旧枚举方法的大量无效完整评估。
            路径数 = len(个体序列) // 容量
            候选路线 = random.sample(range(路径数), min(5, 路径数))
            # 两个版本执行相同的负担代理计算；Matched-Random16只是不使用排序结果。
            路线负担 = {
                r: sum(self._位置负担(个体序列, r * 容量 + j) for j in range(容量))
                for r in 候选路线
            }
            路径 = (
                max(候选路线, key=lambda r: 路线负担[r])
                if self._本次使用负担排序()
                else random.choice(候选路线)
            )
            起点 = 路径 * 容量
            当前路径 = 个体序列[起点:起点 + 容量]
            全局统计 = self._全局充分统计(个体序列) if self.复合负担代理 else None

            def 路线候选分数(候选路径):
                if self.复合负担代理:
                    return self._替换路线复合代理(
                        全局统计, [当前路径], [候选路径]
                    )
                return self._路径距离(候选路径)

            if 容量 <= 7:
                最优路径 = list(min(
                    itertools.permutations(当前路径), key=路线候选分数
                ))
            else:
                # XML100的车辆容量可能达到25，完整枚举Q!只适用于原Q=4实例；
                # 大容量时改为固定24个路径内反转候选，保持算法可扩展且不额外消耗复合目标评估。
                路径候选 = [当前路径[:]]
                for _ in range(24):
                    左, 右 = sorted(random.sample(range(容量), 2))
                    候选路径 = 当前路径[:]
                    候选路径[左:右 + 1] = reversed(候选路径[左:右 + 1])
                    路径候选.append(候选路径)
                最优路径 = min(路径候选, key=路线候选分数)
            新序列 = 个体序列[:]
            新序列[起点:起点 + 容量] = 最优路径
            return 新序列

        客户到位置 = {客户: 位置 for 位置, 客户 in enumerate(个体序列)}
        位置负担表 = [
            self._位置负担(个体序列, 位置) for 位置 in range(len(个体序列))
        ]
        if self._本次使用负担排序():
            重点池 = sorted(
                range(len(个体序列)),
                key=lambda 位置: 位置负担表[位置],
                reverse=True,
            )[:12]
        else:
            重点池 = random.sample(range(len(个体序列)), min(12, len(个体序列)))
        i = random.choice(重点池)
        客户 = 个体序列[i]
        当前块 = i // 容量
        伙伴 = []
        for 其他客户 in self._最近客户[客户]:
            j = 客户到位置[其他客户]
            if j // 容量 != 当前块:
                伙伴.append(j)
            if len(伙伴) >= 8:
                break
        伙伴.extend(random.sample(
            [j for j in range(len(个体序列)) if j // 容量 != 当前块 and j not in 伙伴],
            4,
        ))

        全局统计 = self._全局充分统计(个体序列) if self.复合负担代理 else None

        # 新版本使用受影响路线的充分统计量筛选伙伴，使候选构造与最终F一致；
        # 旧版本仍保留纯距离代理，便于严格回归和消融。
        def 伙伴代理变化(j):
            受影响块 = {当前块, j // 容量}
            原路线 = [
                个体序列[块 * 容量:(块 + 1) * 容量]
                for 块 in 受影响块
            ]
            临时 = 个体序列[:]
            临时[i], 临时[j] = 临时[j], 临时[i]
            新路线 = [
                临时[块 * 容量:(块 + 1) * 容量]
                for 块 in 受影响块
            ]
            if self.复合负担代理:
                return self._替换路线复合代理(全局统计, 原路线, 新路线)
            return (
                sum(self._路径距离(路线) for 路线 in 新路线)
                - sum(self._路径距离(路线) for 路线 in 原路线)
            )

        j = min(伙伴, key=伙伴代理变化)
        新序列 = 个体序列[:]
        新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        return 新序列

    def 运行(self):
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        遗传阶段代数 = int(self.参数.get("遗传阶段代数", 80))
        原代数 = self.参数["迭代次数"]
        原按预算终止 = self.参数.get("GA按有效评价预算终止", True)
        self.参数["迭代次数"] = 遗传阶段代数
        # 混合算法的GA部分按预热代数终止；总有效评价预算由后续局部阶段补足。
        self.参数["GA按有效评价预算终止"] = False
        遗传结果 = super().运行()
        self.参数["迭代次数"] = 原代数
        self.参数["GA按有效评价预算终止"] = 原按预算终止

        当前解 = 遗传结果["最终最优个体"][:]
        当前适应度 = self.工具.适应度计算(当前解, self.距离矩阵)
        最优解, 最优适应度 = 当前解[:], 当前适应度
        历代最优适应度 = 遗传结果["历代最优适应度"][:]
        历代最优个体 = 遗传结果["历代最优个体"][:]
        起始评估 = self.工具.指标评估次数
        无改进次数 = 0
        算子权重 = {
            "任意交换": 1.0,
            "跨路径交换": 1.0,
            "路径内反转": 1.0,
            "路径内重排": 1.0,
            "双客户段交换": 1.0,
            "负担引导": 1.0,
        }
        if self.禁用负担引导:
            del 算子权重["负担引导"]

        while self.工具.指标评估次数 < 目标预算:
            已用局部预算 = self.工具.指标评估次数 - 起始评估
            总局部预算 = max(目标预算 - 起始评估, 1)
            进度 = min(已用局部预算 / 总局部预算, 1.0)
            温度 = 0.010 * (1.0 - 进度) + 0.00005

            批量结果 = []
            批量数 = min(self.候选批量大小, 目标预算 - self.工具.指标评估次数)
            for _ in range(批量数):
                if self.自适应算子:
                    算子 = self._按权重选择算子(算子权重)
                    候选解 = self._按算子生成邻域(当前解, 算子)
                elif self.统一六算子:
                    # Static-VNS16与BRIO-MNS共享候选批量和六类邻域，
                    # 唯一区别是始终按1/6抽样，从而形成公平的自适应机制对照。
                    算子 = random.choice(list(算子权重))
                    候选解 = self._按算子生成邻域(当前解, 算子)
                elif self.启用贡献引导 and random.random() < 0.85:
                    算子 = "负担引导"
                    候选解 = self._引导邻域(当前解)
                else:
                    算子 = "任意交换"
                    候选解 = self._随机邻域(当前解)
                候选适应度 = self.工具.适应度计算(候选解, self.距离矩阵)
                批量结果.append((候选适应度, 候选解, 算子))

                if self.自适应算子:
                    # 用真实复合目标改善作为算子奖励，让实例状态决定邻域概率而非固定70/30切换。
                    if 候选适应度 < 最优适应度 - 1e-12:
                        奖励 = 3.0
                    elif 候选适应度 < 当前适应度 - 1e-12:
                        奖励 = 1.0
                    else:
                        奖励 = 0.0
                    算子权重[算子] = max(0.10, 0.98 * 算子权重[算子] + 0.02 * (0.20 + 奖励))

            候选适应度, 候选解, _ = min(批量结果, key=lambda 项: 项[0])
            差值 = 候选适应度 - 当前适应度
            if 差值 < 0 or random.random() < math.exp(-差值 / max(温度, 1e-12)):
                当前解, 当前适应度 = 候选解, 候选适应度

            if 当前适应度 < 最优适应度 - 1e-12:
                最优解, 最优适应度 = 当前解[:], 当前适应度
                无改进次数 = 0
            else:
                无改进次数 += 1

            if 无改进次数 >= 1200 and self.工具.指标评估次数 < 目标预算:
                # 长期停滞时从历史最优解做两次随机扰动，避免固定70/30阶段无法响应搜索状态。
                当前解 = 最优解[:]
                for _ in range(2):
                    当前解 = self._随机邻域(当前解)
                当前适应度 = self.工具.适应度计算(当前解, self.距离矩阵)
                无改进次数 = 0

            if self.工具.指标评估次数 % 250 == 0:
                历代最优适应度.append(最优适应度)
                历代最优个体.append(最优解[:])

        最终种群 = 遗传结果["最终种群"][:]
        最终种群[0] = 最优解[:]
        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": [],
            "最终种群": 最终种群,
            "最终最优个体": 最优解,
            "指标评估次数": self.工具.指标评估次数,
            "算子权重": 算子权重 if self.自适应算子 else {},
        }


class 预算ACO求解器(GA求解器):
    """在固定容量块编码上直接优化复合目标F的基础蚁群算法。"""

    def __init__(
        self, *args, 蚂蚁数量=20, 信息素权重=1.0, 启发权重=3.0,
        蒸发率=0.20, 候选表大小=20, **kwargs
    ):
        super().__init__(*args, **kwargs)
        # 允许批量实验脚本通过公共参数覆盖ACO设置，便于复盘时受控调参。
        self.蚂蚁数量 = max(1, int(self.参数.get("ACO蚂蚁数量", 蚂蚁数量)))
        self.信息素权重 = float(self.参数.get("ACO信息素权重", 信息素权重))
        self.启发权重 = float(self.参数.get("ACO启发权重", 启发权重))
        self.蒸发率 = min(max(float(self.参数.get("ACO蒸发率", 蒸发率)), 1e-6), 0.999999)
        self.候选表大小 = max(1, int(self.参数.get("ACO候选表大小", 候选表大小)))
        self._最近客户 = {
            当前: sorted(
                range(1, self.客户数量 + 1),
                key=lambda 客户: self.距离矩阵[当前][客户],
            )
            for 当前 in range(self.客户数量 + 1)
        }

    @staticmethod
    def _轮盘选择(候选, 权重):
        总权重 = sum(权重)
        if not math.isfinite(总权重) or 总权重 <= 0:
            return random.choice(候选)
        阈值 = random.random() * 总权重
        累计 = 0.0
        for 客户, 值 in zip(候选, 权重):
            累计 += 值
            if 累计 >= 阈值:
                return 客户
        return 候选[-1]

    def _构造蚂蚁解(self, 信息素):
        # 固定块编码下每Q个客户自然构成一条容量可行路线；
        # 信息素负责学习常共同出现的边，距离倒数作为基础ACO的局部启发值。
        容量 = self.参数["车辆容量"]
        未访问 = set(range(1, self.客户数量 + 1))
        解 = []
        for _ in range(self.客户数量 // 容量):
            当前 = 0
            for _ in range(容量):
                近邻候选 = [
                    客户 for 客户 in self._最近客户[当前][:self.候选表大小]
                    if 客户 in 未访问
                ]
                候选 = 近邻候选 or list(未访问)
                权重 = []
                for 客户 in 候选:
                    启发值 = 1.0 / max(float(self.距离矩阵[当前][客户]), 1e-9)
                    权重.append(
                        max(信息素[当前][客户], 1e-12) ** self.信息素权重
                        * 启发值 ** self.启发权重
                    )
                下一个 = self._轮盘选择(候选, 权重)
                解.append(下一个)
                未访问.remove(下一个)
                当前 = 下一个
        return 解

    def _信息素边(self, 个体序列):
        容量 = self.参数["车辆容量"]
        for 起点 in range(0, len(个体序列), 容量):
            前客户 = 0
            for 客户 in 个体序列[起点:起点 + 容量]:
                yield 前客户, 客户
                前客户 = 客户
            yield 前客户, 0

    def _沉积信息素(self, 信息素, 个体序列, 增量):
        for a, b in self._信息素边(个体序列):
            信息素[a][b] += 增量
            信息素[b][a] += 增量

    def 运行(self):
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        最优解 = self._获取最优个体(self.初始种群)[:]
        最优适应度 = self.工具.适应度计算(最优解, self.距离矩阵)
        信息素 = [
            [1.0 for _ in range(self.客户数量 + 1)]
            for _ in range(self.客户数量 + 1)
        ]
        self._沉积信息素(信息素, 最优解, 1.0 / max(最优适应度, 1e-12))
        历代最优适应度 = [最优适应度]
        历代最优个体 = [最优解[:]]

        while self.工具.指标评估次数 < 目标预算:
            本轮 = []
            数量 = min(self.蚂蚁数量, 目标预算 - self.工具.指标评估次数)
            for _ in range(数量):
                候选解 = self._构造蚂蚁解(信息素)
                候选适应度 = self.工具.适应度计算(候选解, self.距离矩阵)
                本轮.append((候选适应度, 候选解))
                if 候选适应度 < 最优适应度 - 1e-12:
                    最优解, 最优适应度 = 候选解[:], 候选适应度

            # 按基础Ant System规则先全局蒸发，再由本轮所有完整解按1/F沉积；
            # 每只蚂蚁只在完整解形成后调用一次真实复合目标，评估预算与其他算法可核对。
            保留率 = 1.0 - self.蒸发率
            for i in range(self.客户数量 + 1):
                for j in range(self.客户数量 + 1):
                    信息素[i][j] = max(1e-12, 信息素[i][j] * 保留率)
            for 候选适应度, 候选解 in 本轮:
                增量 = 1.0 / (max(候选适应度, 1e-12) * max(数量, 1))
                self._沉积信息素(信息素, 候选解, 增量)

            历代最优适应度.append(最优适应度)
            历代最优个体.append(最优解[:])

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": [],
            "最终种群": [最优解[:]],
            "最终最优个体": 最优解,
            "指标评估次数": self.工具.指标评估次数,
        }


class 预算ALNS求解器(GA求解器):
    """使用三类破坏和三类修复算子的同目标、同预算ALNS基线。"""

    def __init__(self, *args, 移除比例=0.10, **kwargs):
        super().__init__(*args, **kwargs)
        # 通过实验脚本暴露移除比例，便于检查ALNS优势是否依赖特定破坏尺度。
        self.移除比例 = min(
            max(float(self.参数.get("ALNS移除比例", 移除比例)), 0.02), 0.40
        )

    @staticmethod
    def _按权重选择(权重表):
        总权重 = sum(权重表.values())
        阈值 = random.random() * 总权重
        累计 = 0.0
        for 名称, 权重 in 权重表.items():
            累计 += 权重
            if 累计 >= 阈值:
                return 名称
        return next(reversed(权重表))

    def _位置负担(self, 个体序列, 位置):
        容量 = self.参数["车辆容量"]
        块起点 = (位置 // 容量) * 容量
        块终点 = 块起点 + 容量
        块内位置 = 位置 - 块起点
        客户 = 个体序列[位置]
        前客户 = 0 if 位置 == 块起点 else 个体序列[位置 - 1]
        后客户 = 0 if 位置 == 块终点 - 1 else 个体序列[位置 + 1]
        入载荷 = (容量 - 块内位置) / 容量
        出载荷 = max(容量 - 块内位置 - 1, 0) / 容量
        return (self.距离矩阵[前客户][客户] * (1.0 + 入载荷)
                + self.距离矩阵[客户][后客户] * (1.0 + 出载荷))

    def _破坏(self, 个体序列, 算子, 移除数):
        if 算子 == "随机移除":
            移除客户 = random.sample(个体序列, 移除数)
        elif 算子 == "高负担移除":
            重点位置 = sorted(
                range(len(个体序列)),
                key=lambda 位置: self._位置负担(个体序列, 位置),
                reverse=True,
            )[:min(len(个体序列), 移除数 * 3)]
            移除客户 = [个体序列[i] for i in random.sample(重点位置, 移除数)]
        elif 算子 == "相关移除":
            种子客户 = random.choice(个体序列)
            移除客户 = [种子客户] + sorted(
                (客户 for 客户 in 个体序列 if 客户 != 种子客户),
                key=lambda 客户: self.距离矩阵[种子客户][客户],
            )[:移除数 - 1]
        else:
            raise ValueError(f"未知ALNS破坏算子: {算子}")

        移除集合 = set(移除客户)
        容量 = self.参数["车辆容量"]
        路线 = [
            [客户 for 客户 in 个体序列[i:i + 容量] if 客户 not in 移除集合]
            for i in range(0, len(个体序列), 容量)
        ]
        return 路线, 移除客户

    def _插入代价(self, 路线, 位置, 客户):
        前客户 = 0 if 位置 == 0 else 路线[位置 - 1]
        后客户 = 0 if 位置 == len(路线) else 路线[位置]
        return (self.距离矩阵[前客户][客户]
                + self.距离矩阵[客户][后客户]
                - self.距离矩阵[前客户][后客户])

    def _可行插入(self, 路线列表, 客户):
        容量 = self.参数["车辆容量"]
        候选 = []
        for 路线号, 路线 in enumerate(路线列表):
            if len(路线) >= 容量:
                continue
            for 位置 in range(len(路线) + 1):
                候选.append((self._插入代价(路线, 位置, 客户), 路线号, 位置))
        return sorted(候选)

    def _修复(self, 路线列表, 移除客户, 算子):
        待插入 = 移除客户[:]
        random.shuffle(待插入)
        if 算子 == "随机插入":
            for 客户 in 待插入:
                候选 = self._可行插入(路线列表, 客户)
                _, 路线号, 位置 = random.choice(候选)
                路线列表[路线号].insert(位置, 客户)
        elif 算子 == "贪婪插入":
            while 待插入:
                最优 = min(
                    (self._可行插入(路线列表, 客户)[0], 客户)
                    for 客户 in 待插入
                )
                (代价, 路线号, 位置), 客户 = 最优
                路线列表[路线号].insert(位置, 客户)
                待插入.remove(客户)
        elif 算子 == "后悔2插入":
            while 待插入:
                最佳客户 = None
                最佳位置 = None
                最大后悔值 = -math.inf
                for 客户 in 待插入:
                    候选 = self._可行插入(路线列表, 客户)
                    后悔值 = (候选[1][0] - 候选[0][0]) if len(候选) > 1 else math.inf
                    if 后悔值 > 最大后悔值:
                        最大后悔值 = 后悔值
                        最佳客户 = 客户
                        最佳位置 = 候选[0]
                _, 路线号, 位置 = 最佳位置
                路线列表[路线号].insert(位置, 最佳客户)
                待插入.remove(最佳客户)
        else:
            raise ValueError(f"未知ALNS修复算子: {算子}")
        return [客户 for 路线 in 路线列表 for 客户 in 路线]

    def 运行(self):
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        当前解 = self._获取最优个体(self.初始种群)[:]
        当前适应度 = self.工具.适应度计算(当前解, self.距离矩阵)
        最优解, 最优适应度 = 当前解[:], 当前适应度
        起始评估 = self.工具.指标评估次数
        破坏权重 = {"随机移除": 1.0, "高负担移除": 1.0, "相关移除": 1.0}
        修复权重 = {"随机插入": 1.0, "贪婪插入": 1.0, "后悔2插入": 1.0}
        历代最优适应度 = [最优适应度]
        历代最优个体 = [最优解[:]]
        无改进次数 = 0

        while self.工具.指标评估次数 < 目标预算:
            已用 = self.工具.指标评估次数 - 起始评估
            可用 = max(目标预算 - 起始评估, 1)
            进度 = min(已用 / 可用, 1.0)
            温度 = 0.010 * (1.0 - 进度) + 0.00005
            破坏算子 = self._按权重选择(破坏权重)
            修复算子 = self._按权重选择(修复权重)
            移除数 = min(
                max(2, int(round(self.客户数量 * self.移除比例))),
                self.客户数量 - 1,
            )
            路线列表, 移除客户 = self._破坏(当前解, 破坏算子, 移除数)
            候选解 = self._修复(路线列表, 移除客户, 修复算子)
            候选适应度 = self.工具.适应度计算(候选解, self.距离矩阵)
            差值 = 候选适应度 - 当前适应度
            接受 = 差值 < 0 or random.random() < math.exp(-差值 / max(温度, 1e-12))
            if 候选适应度 < 最优适应度 - 1e-12:
                奖励 = 5.0
            elif 候选适应度 < 当前适应度 - 1e-12:
                奖励 = 3.0
            elif 接受:
                奖励 = 1.0
            else:
                奖励 = 0.0

            # ALNS破坏与修复算子只根据真实F产生的结果获得奖励，
            # 距离增量仅用于廉价修复，不额外计作一次完整目标评价。
            破坏权重[破坏算子] = max(
                0.10, 0.90 * 破坏权重[破坏算子] + 0.10 * (0.20 + 奖励)
            )
            修复权重[修复算子] = max(
                0.10, 0.90 * 修复权重[修复算子] + 0.10 * (0.20 + 奖励)
            )
            if 接受:
                当前解, 当前适应度 = 候选解, 候选适应度
            if 当前适应度 < 最优适应度 - 1e-12:
                最优解, 最优适应度 = 当前解[:], 当前适应度
                无改进次数 = 0
            else:
                无改进次数 += 1
            if 无改进次数 >= 1200:
                当前解, 当前适应度 = 最优解[:], 最优适应度
                无改进次数 = 0
            if self.工具.指标评估次数 % 250 == 0:
                历代最优适应度.append(最优适应度)
                历代最优个体.append(最优解[:])

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": [],
            "最终种群": [最优解[:]],
            "最终最优个体": 最优解,
            "指标评估次数": self.工具.指标评估次数,
            "算子权重": {"破坏": 破坏权重, "修复": 修复权重},
        }


class 预算TS求解器(GA求解器):
    """采用交换邻域、禁忌任期和特赦准则的基础同目标TS基线。"""

    def __init__(self, *args, 候选数量=20, 禁忌任期=7, **kwargs):
        super().__init__(*args, **kwargs)
        # 恢复多基线实验需要的基础TS；固定候选表和短期记忆，
        # 不额外引入路线专用强化模块，保证实现边界可复盘。
        self.候选数量 = max(2, int(self.参数.get("TS候选数量", 候选数量)))
        self.禁忌任期 = max(2, int(self.参数.get("TS禁忌任期", 禁忌任期)))

    def 运行(self):
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        当前解 = self._获取最优个体(self.初始种群)[:]
        当前适应度 = self.工具.适应度计算(当前解, self.距离矩阵)
        最优解, 最优适应度 = 当前解[:], 当前适应度
        禁忌截止 = {}
        迭代 = 0
        历代最优适应度 = [最优适应度]
        历代最优个体 = [最优解[:]]

        while self.工具.指标评估次数 < 目标预算:
            迭代 += 1
            剩余预算 = 目标预算 - self.工具.指标评估次数
            本轮数量 = min(self.候选数量, 剩余预算)
            已抽移动 = set()
            全部候选 = []
            可接受候选 = []
            while len(全部候选) < 本轮数量:
                i, j = sorted(random.sample(range(len(当前解)), 2))
                移动 = tuple(sorted((当前解[i], 当前解[j])))
                if 移动 in 已抽移动:
                    continue
                已抽移动.add(移动)
                候选解 = 当前解[:]
                候选解[i], 候选解[j] = 候选解[j], 候选解[i]
                候选适应度 = self.工具.适应度计算(候选解, self.距离矩阵)
                项 = (候选适应度, 候选解, 移动)
                全部候选.append(项)
                if 禁忌截止.get(移动, -1) <= 迭代 or 候选适应度 < 最优适应度 - 1e-12:
                    可接受候选.append(项)

            当前适应度, 当前解, 采用移动 = min(
                可接受候选 or 全部候选, key=lambda 项: 项[0]
            )
            禁忌截止[采用移动] = 迭代 + self.禁忌任期 + random.randint(0, 2)
            if 当前适应度 < 最优适应度 - 1e-12:
                最优解, 最优适应度 = 当前解[:], 当前适应度
            历代最优适应度.append(最优适应度)
            历代最优个体.append(最优解[:])

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": [],
            "最终种群": [最优解[:]],
            "最终最优个体": 最优解,
            "指标评估次数": self.工具.指标评估次数,
        }


class 预算DPSO求解器(GA求解器):
    """使用交换序列表示速度的基础离散粒子群复合目标基线。"""

    def __init__(
        self, *args, 粒子数量=20, 最大交换数=6,
        个体学习概率=0.50, 社会学习概率=0.75, 随机扰动概率=0.15, **kwargs
    ):
        super().__init__(*args, **kwargs)
        # 恢复基础DPSO，并采用排列问题的交换序列表示，确保每个粒子
        # 始终是无重复、无遗漏的合法客户排列。
        self.粒子数量 = max(2, int(self.参数.get("DPSO粒子数量", 粒子数量)))
        self.最大交换数 = max(1, int(self.参数.get("DPSO最大交换数", 最大交换数)))
        self.个体学习概率 = min(max(float(self.参数.get(
            "DPSO个体学习概率", 个体学习概率
        )), 0.0), 1.0)
        self.社会学习概率 = min(max(float(self.参数.get(
            "DPSO社会学习概率", 社会学习概率
        )), 0.0), 1.0)
        self.随机扰动概率 = min(max(float(self.参数.get(
            "DPSO随机扰动概率", 随机扰动概率
        )), 0.0), 1.0)

    @staticmethod
    def _差分交换序列(源序列, 目标序列, 上限):
        工作序列 = 源序列[:]
        客户位置 = {客户: 位置 for 位置, 客户 in enumerate(工作序列)}
        交换序列 = []
        for i, 目标客户 in enumerate(目标序列):
            if 工作序列[i] == 目标客户:
                continue
            j = 客户位置[目标客户]
            被换客户 = 工作序列[i]
            工作序列[i], 工作序列[j] = 工作序列[j], 工作序列[i]
            客户位置[目标客户] = i
            客户位置[被换客户] = j
            交换序列.append((i, j))
            if len(交换序列) >= 上限:
                break
        return 交换序列

    @staticmethod
    def _应用交换序列(个体, 交换序列):
        新个体 = 个体[:]
        for i, j in 交换序列:
            新个体[i], 新个体[j] = 新个体[j], 新个体[i]
        return 新个体

    def 运行(self):
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        粒子数 = min(self.粒子数量, len(self.初始种群), 目标预算)
        粒子 = [个体[:] for 个体 in self.初始种群[:粒子数]]
        当前适应度 = [
            self.工具.适应度计算(个体, self.距离矩阵) for 个体 in 粒子
        ]
        个体最优 = [个体[:] for 个体 in 粒子]
        个体最优适应度 = 当前适应度[:]
        最优编号 = min(range(粒子数), key=lambda k: 个体最优适应度[k])
        全局最优 = 个体最优[最优编号][:]
        全局最优适应度 = 个体最优适应度[最优编号]
        速度 = [[] for _ in range(粒子数)]
        历代最优适应度 = [全局最优适应度]
        历代最优个体 = [全局最优[:]]

        while self.工具.指标评估次数 < 目标预算:
            进度 = self.工具.指标评估次数 / max(目标预算, 1)
            惯性概率 = 0.80 * (1.0 - 进度) + 0.30 * 进度
            for k in range(粒子数):
                if self.工具.指标评估次数 >= 目标预算:
                    break
                保留速度 = [移动 for 移动 in 速度[k] if random.random() < 惯性概率]
                个体差分 = self._差分交换序列(
                    粒子[k], 个体最优[k], self.最大交换数
                )
                全局差分 = self._差分交换序列(
                    粒子[k], 全局最优, self.最大交换数
                )
                学习速度 = (
                    保留速度
                    + [移动 for 移动 in 个体差分 if random.random() < self.个体学习概率]
                    + [移动 for 移动 in 全局差分 if random.random() < self.社会学习概率]
                )[:self.最大交换数]
                if not 学习速度 or random.random() < self.随机扰动概率:
                    学习速度.append(tuple(sorted(random.sample(range(len(粒子[k])), 2))))
                速度[k] = 学习速度[-self.最大交换数:]
                候选粒子 = self._应用交换序列(粒子[k], 速度[k])
                候选适应度 = self.工具.适应度计算(候选粒子, self.距离矩阵)
                粒子[k], 当前适应度[k] = 候选粒子, 候选适应度
                if 候选适应度 < 个体最优适应度[k] - 1e-12:
                    个体最优[k] = 候选粒子[:]
                    个体最优适应度[k] = 候选适应度
                    if 候选适应度 < 全局最优适应度 - 1e-12:
                        全局最优 = 候选粒子[:]
                        全局最优适应度 = 候选适应度
            历代最优适应度.append(全局最优适应度)
            历代最优个体.append(全局最优[:])

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": [],
            "最终种群": [全局最优[:]],
            "最终最优个体": 全局最优,
            "指标评估次数": self.工具.指标评估次数,
        }


