def 汇总(全部结果):
    汇总结果 = {}
    for 名称 in sorted({行["算法"] for 行 in 全部结果}):
        行组 = [行 for 行 in 全部结果 if 行["算法"] == 名称]
        值 = [行["复合目标"] for 行 in 行组]
        汇总结果[名称] = {
            "均值": statistics.mean(值),
            "标准差": statistics.stdev(值) if len(值) > 1 else 0.0,
            "最优": min(值),
            "指标评估次数均值": statistics.mean(行["指标评估次数"] for 行 in 行组),
            "耗时秒均值": statistics.mean(行["耗时秒"] for 行 in 行组),
        }
    if "GA" in 汇总结果:
        GA均值 = 汇总结果["GA"]["均值"]
        for 名称, 值 in 汇总结果.items():
            值["相对GA改善率"] = (GA均值 - 值["均值"]) / GA均值
    else:
        for 值 in 汇总结果.values():
            值["相对GA改善率"] = None
    return 汇总结果


