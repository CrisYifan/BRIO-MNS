import copy
import random
import math
from utils import 工具类


class 基础求解器:
    """基础求解器类"""

    def __init__(self, 参数配置, 点列表, 距离矩阵, 仓库坐标, 初始种群=None):
        self.参数 = 参数配置
        self.点列表 = 点列表
        self.距离矩阵 = 距离矩阵
        self.仓库坐标 = 仓库坐标
        self.工具 = 工具类(参数配置)
        self.客户数量 = len(点列表) - 1

        # 创建禁忌表
        # 去除固定100客户的硬编码，使算法能按数据集规模创建合法排列。
        self.禁忌表 = list(range(1, self.客户数量 + 1))
        self.节约值矩阵 = self._创建节约值矩阵()
        # 允许SVGA与GA共享完全相同的初始种群，避免初始化差异污染对比结果。
        self.初始种群 = (copy.deepcopy(初始种群)
                         if 初始种群 is not None else self._初始化种群())

    def _创建节约值矩阵(self):
        """创建节约值矩阵"""
        节约值矩阵 = []
        for 索引自身, 距离 in enumerate(self.距离矩阵[1:self.客户数量 + 1]):
            节约值子列表 = []
            for 索引, 距 in enumerate(距离):
                节约值 = self.距离矩阵[0][索引自身 + 1] + self.距离矩阵[0][索引] - 距
                if 节约值 < 0:
                    节约值 = 0
                节约值子列表.append(节约值)
            节约值矩阵.append(节约值子列表)
        return 节约值矩阵

    def _初始化种群(self):
        """初始化种群"""
        初始种群 = []
        随机种群数 = int(self.参数["初始种群数量"] * self.参数["随机种群比例"])

        # 随机生成部分个体
        for _ in range(随机种群数):
            随机个体 = random.sample(range(1, self.客户数量 + 1), self.客户数量)
            初始种群.append(随机个体)

        # 用节约值法生成剩余个体
        插入种群数 = int(self.参数["初始种群数量"] * self.参数["插入种群比例"])
        for _ in range(插入种群数):
            子个体 = []
            种群禁忌表 = copy.deepcopy(self.禁忌表)
            起点禁忌表 = copy.deepcopy(self.禁忌表)

            for _ in range((len(self.距离矩阵) - 1) // self.参数["车辆容量"]):
                环路 = []
                起点 = random.choice(起点禁忌表)
                环路.append(起点)

                # 计算节约值排序
                节约值排序列表 = []
                for k in range(1, len(self.节约值矩阵[起点 - 1])):
                    节约值排序列表.append((k, self.节约值矩阵[起点 - 1][k]))

                # 标记已使用点
                for k in range(len(种群禁忌表)):
                    if 种群禁忌表[k] == -1:
                        节约值排序列表[k] = list(节约值排序列表[k])
                        节约值排序列表[k][1] = -1
                        节约值排序列表[k] = tuple(节约值排序列表[k])

                排序数据 = sorted(节约值排序列表, key=lambda x: x[1], reverse=True)

                # 移除起点自身
                for k in range(len(排序数据)):
                    if 排序数据[k][0] == 起点:
                        del 排序数据[k]
                        break

                # 形成环路
                for k in range(self.参数["车辆容量"] - 1):
                    环路.append(排序数据[k][0])

                # 更新禁忌表
                for k in range(len(环路)):
                    种群禁忌表[环路[k] - 1] = -1

                for k in range(len(环路)):
                    if 环路[k] in 起点禁忌表:
                        起点禁忌表.remove(环路[k])

                for k in range(len(环路)):
                    子个体.append(环路[k])

            初始种群.append(子个体)

        return 初始种群

    def _选择交叉(self, 种群, 精英数量, 父代数量):
        """选择和交叉操作"""
        交叉后种群 = []

        # 计算适应度并排序
        排序种群 = []
        for 个体 in 种群:
            适应度值 = self.工具.适应度计算(个体, self.距离矩阵)
            排序种群.append((个体, 适应度值))

        排序种群.sort(key=lambda x: x[1])

        # 保留精英
        for i in range(min(精英数量, len(排序种群))):
            交叉后种群.append(排序种群[i][0])

        # 选择父代
        父代列表 = []
        for i in range(min(父代数量, len(排序种群))):
            父代列表.append(排序种群[i][0])

        # 交叉操作
        for _ in range((len(种群) - 精英数量) // 2):
            选择索引 = random.sample(range(len(父代列表)), 2)
            父代1 = 父代列表[选择索引[0]]
            父代2 = 父代列表[选择索引[1]]

            子代对 = self.工具.OX交叉(父代1, 父代2, self.禁忌表)
            交叉后种群.append(子代对[0])
            交叉后种群.append(子代对[1])

        return 交叉后种群

    def _获取最优个体(self, 种群):
        """获取种群中的最优个体"""
        最优适应度 = float('inf')
        最优个体 = 种群[0] if 种群 else None

        for 个体 in 种群:
            适应度值 = self.工具.适应度计算(个体, self.距离矩阵)
            if 适应度值 < 最优适应度:
                最优适应度 = 适应度值
                最优个体 = 个体

        return 最优个体


class SVGA求解器(基础求解器):
    """基于Shapley值的遗传算法求解器"""

    def _构造块内局部代理(self, 个体序列, 位置):
        """用块内相邻交换构造保持排列与容量约束的局部代理。"""
        局部代理 = 个体序列[:]
        车辆容量 = self.参数["车辆容量"]
        块起点 = (位置 // 车辆容量) * 车辆容量
        块终点 = min(块起点 + 车辆容量, len(个体序列)) - 1

        # 旧实现用相邻节点覆盖当前位置，会产生重复节点并丢失一个客户；
        # 这里改为块内相邻交换，保证局部代理始终是合法完整排列，且不改变车辆客户集合。
        if 位置 < 块终点:
            相邻位置 = 位置 + 1
        elif 位置 > 块起点:
            相邻位置 = 位置 - 1
        else:
            return 局部代理

        局部代理[位置], 局部代理[相邻位置] = 局部代理[相邻位置], 局部代理[位置]
        return 局部代理

    def _计算Shapley贡献值(self, 个体序列):
        """计算Shapley贡献值"""
        shapley值列表 = []
        原指标 = self.工具.路径指标计算(个体序列, self.距离矩阵)
        原路径长 = 原指标[2]
        原路径均衡 = 原指标[3]
        原负载均衡 = 原指标[4]

        for i in range(len(个体序列)):
            个体副本 = self._构造块内局部代理(个体序列, i)

            新指标 = self.工具.路径指标计算(个体副本, self.距离矩阵)
            新路径长 = 新指标[2]
            新路径均衡 = 新指标[3]
            新负载均衡 = 新指标[4]

            路径长差异 = abs(新路径长 - 原路径长)
            路径均衡差异 = abs(新路径均衡 - 原路径均衡)
            负载均衡差异 = abs(新负载均衡 - 原负载均衡)

            # 计算贡献值（反比）
            路径贡献 = 1 / (1 + 路径长差异)
            均衡贡献 = 1 / (1 + 路径均衡差异)
            负载贡献 = 1 / (1 + 负载均衡差异)

            shapley值 = (self.参数["路径扰动权重"] * 路径贡献 +
                         self.参数["路径均衡扰动权重"] * 均衡贡献 +
                         self.参数["负载均衡扰动权重"] * 负载贡献)
            shapley值列表.append(shapley值)

        return shapley值列表

    def _计算Shapley扰动值(self, 个体序列):
        """计算Shapley扰动值"""
        shapley值列表 = []
        原指标 = self.工具.路径指标计算(个体序列, self.距离矩阵)
        原路径长 = 原指标[2]
        原路径均衡 = 原指标[3]
        原负载均衡 = 原指标[4]

        for i in range(len(个体序列)):
            个体副本 = self._构造块内局部代理(个体序列, i)

            新指标 = self.工具.路径指标计算(个体副本, self.距离矩阵)
            新路径长 = 新指标[2]
            新路径均衡 = 新指标[3]
            新负载均衡 = 新指标[4]

            路径长差异 = abs(新路径长 - 原路径长)
            路径均衡差异 = abs(新路径均衡 - 原路径均衡)
            负载均衡差异 = abs(新负载均衡 - 原负载均衡)

            shapley值 = (self.参数["路径扰动权重"] * 路径长差异 +
                         self.参数["路径均衡扰动权重"] * 路径均衡差异 +
                         self.参数["负载均衡扰动权重"] * 负载均衡差异)
            shapley值列表.append(shapley值)

        return shapley值列表

    def _枚举交换变异(self, 个体序列, 候选位置列表):
        """围绕Shapley候选位置枚举受限的合法交换邻域。"""
        if not 候选位置列表:
            return 个体序列[:]

        原适应度 = self.工具.适应度计算(个体序列, self.距离矩阵)
        最优序列 = 个体序列[:]
        最优适应度 = 原适应度

        # 完整排列不存在“未使用节点”，旧枚举替换分支永远不可达；
        # 改为枚举合法swap邻域，并限制伙伴数量以控制后期精修计算量。
        可选伙伴 = [i for i in range(len(个体序列)) if i not in 候选位置列表]
        伙伴数量 = min(self.参数.get("收敛枚举伙伴数量", 12), len(可选伙伴))
        伙伴位置列表 = random.sample(可选伙伴, 伙伴数量) if 伙伴数量 > 0 else []

        # 同时加入候选点的块内邻居，保留对局部路径次序的精细搜索能力。
        车辆容量 = self.参数["车辆容量"]
        for 位置 in 候选位置列表:
            块起点 = (位置 // 车辆容量) * 车辆容量
            块终点 = min(块起点 + 车辆容量, len(个体序列))
            for 相邻位置 in range(块起点, 块终点):
                if 相邻位置 != 位置 and 相邻位置 not in 伙伴位置列表:
                    伙伴位置列表.append(相邻位置)

        已评估交换 = set()
        for 位置 in 候选位置列表:
            for 伙伴位置 in 伙伴位置列表:
                if 位置 == 伙伴位置:
                    continue
                交换对 = tuple(sorted((位置, 伙伴位置)))
                if 交换对 in 已评估交换:
                    continue
                已评估交换.add(交换对)

                新序列 = 个体序列[:]
                新序列[位置], 新序列[伙伴位置] = 新序列[伙伴位置], 新序列[位置]
                新适应度 = self.工具.适应度计算(新序列, self.距离矩阵)
                if 新适应度 < 最优适应度:
                    最优适应度 = 新适应度
                    最优序列 = 新序列

        # 收敛阶段使用best-improvement，只接受严格改进，避免破坏后期优良结构。
        return 最优序列

    def _探索阶段变异(self, 个体序列):
        """
        探索阶段变异：使用Shapley贡献值选择一个交换端点。
        """
        shapley使用概率 = random.uniform(0, 1)
        shapley应用概率阈值 = self.参数["shapley应用概率"]

        if shapley使用概率 <= shapley应用概率阈值:
            # 使用Shapley贡献值选择变异点
            shapley值列表 = self._计算Shapley贡献值(个体序列)

            # 选择贡献值最大的前K个位置作为候选
            shapley元组列表 = [(i, shapley值列表[i]) for i in range(len(个体序列))]
            shapley元组列表.sort(key=lambda x: x[1], reverse=True)

            候选数量 = min(self.参数.get("探索候选位置数量", 10), len(shapley元组列表))
            候选点 = shapley元组列表[:候选数量]
            总贡献值 = sum(值 for _, 值 in 候选点)

            if 总贡献值 > 0:
                随机值 = random.uniform(0, 1)
                累计值 = 0
                变异点 = None

                for 索引, 值 in 候选点:
                    累计值 += 值
                    if 累计值 / 总贡献值 >= 随机值:
                        变异点 = 索引
                        break

                if 变异点 is not None and 变异点 < len(个体序列):
                    # 旧代码选出Shapley候选后又随机选择两个点，候选没有进入实际动作；
                    # 这里固定候选点为交换一端，使Shapley排序真正影响探索变异。
                    伙伴候选 = [j for j in range(len(个体序列)) if j != 变异点]
                    伙伴位置 = random.choice(伙伴候选)
                    新序列 = 个体序列[:]
                    新序列[变异点], 新序列[伙伴位置] = 新序列[伙伴位置], 新序列[变异点]
                    return 新序列

        # 随机交换变异（作为备选）
        i, j = random.sample(range(len(个体序列)), 2)
        新序列 = 个体序列[:]
        新序列[i], 新序列[j] = 新序列[j], 新序列[i]
        return 新序列

    def _收敛阶段变异(self, 个体序列):
        """
        收敛阶段变异：选择多个高扰动候选位置进行枚举交换精修。
        """
        # 计算Shapley扰动值来识别需要改进的位置
        shapley值列表 = self._计算Shapley扰动值(个体序列)

        # 选择扰动值最大的前N个位置（最需要改进的位置）
        shapley元组列表 = [(i, shapley值列表[i]) for i in range(len(个体序列))]
        shapley元组列表.sort(key=lambda x: x[1], reverse=True)

        # 收敛阶段选择更多候选位置进行枚举
        候选位置数 = min(self.参数.get("收敛候选位置数量", 8), len(个体序列))
        候选位置 = [索引 for 索引, _ in shapley元组列表[:候选位置数]]

        # 使用合法的枚举交换变异
        return self._枚举交换变异(个体序列, 候选位置)

    def _变异操作(self, 个体序列, 当前代数, 总代数):
        """
        SVGA变异操作（改进版）
        阶段划分：
        - 探索阶段（0-70%）：使用Shapley贡献值主导的探索
        - 收敛阶段（70-100%）：使用枚举替换变异，精细搜索（30%）
        """
        # 变异概率只在统一入口判断一次，避免与Shapley应用概率嵌套后难以解释。
        if random.random() >= self.参数["变异概率"]:
            return 个体序列[:]

        # 探索阶段比例设为70%，收敛阶段占30%
        探索阶段比例 = self.参数.get("探索阶段比例", 0.70)

        # 判断当前阶段
        if 当前代数 < 总代数 * 探索阶段比例:
            # 探索阶段
            return self._探索阶段变异(个体序列)
        else:
            # 收敛阶段（30%的迭代次数）
            return self._收敛阶段变异(个体序列)

    def 运行(self):
        """运行SVGA算法"""
        种群 = copy.deepcopy(self.初始种群)
        历代最优适应度 = []
        历代最优个体 = []
        历代全部种群 = []

        总代数 = self.参数["迭代次数"]
        探索阶段比例 = self.参数.get("探索阶段比例", 0.70)
        探索代数阈值 = int(总代数 * 探索阶段比例)

        for 代数 in range(总代数):
            # 选择和交叉
            种群 = self._选择交叉(种群,
                                  self.参数["精英保留数量"],
                                  self.参数["父代选择数量"])

            # 变异
            # 精英必须原样进入下一代；旧实现再次变异前4个精英，实际未实现精英保留。
            for i in range(self.参数["精英保留数量"], len(种群)):
                种群[i] = self._变异操作(种群[i], 代数, 总代数)
            # 完整保存200代×1000个体会占用大量内存；仅在显式要求时记录全部种群。
            if self.参数.get("记录全部种群", False):
                历代全部种群.append(copy.deepcopy(种群))

            # 记录最优解
            最优个体 = self._获取最优个体(种群)
            历代最优个体.append(最优个体)

            最优适应度 = self.工具.适应度计算(最优个体, self.距离矩阵)
            历代最优适应度.append(最优适应度)

            指标 = self.工具.路径指标计算(最优个体, self.距离矩阵)

            # 显示当前阶段
            if 代数 < 探索代数阈值:
                阶段标记 = "探索"
            else:
                阶段标记 = "收敛"

            if self.参数.get("输出逐代日志", True):
                print(f"SVGA 第{代数 + 1:3d}代[{阶段标记}]｜适应度={最优适应度:10.2f} | "
                      f"路径长={指标[2]:6d}  路径均衡={指标[3]:9.2f}  "
                      f"负载均衡={指标[4]:9.2f}")

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": 历代全部种群,
            "最终种群": copy.deepcopy(种群),
            "最终最优个体": self._获取最优个体(种群),
            "指标评估次数": self.工具.指标评估次数,
        }


class GA求解器(基础求解器):
    """标准遗传算法求解器"""

    def _变异操作(self, 个体序列):
        """GA变异操作（随机交换）"""
        if random.random() < self.参数["变异概率"]:
            i, j = random.sample(range(len(个体序列)), 2)
            个体序列[i], 个体序列[j] = 个体序列[j], 个体序列[i]
        return 个体序列

    def _运行发布级协议(self):
        """缓存适应度并以有效新解评价数控制预算，排除日志和重复染色体评价。"""
        目标预算 = int(self.参数.get("指标评估预算", 32480))
        按预算终止 = bool(self.参数.get("GA按有效评价预算终止", True))
        最大代数 = int(self.参数["迭代次数"])
        精英数量 = int(self.参数["精英保留数量"])
        父代数量 = int(self.参数["父代选择数量"])
        种群 = copy.deepcopy(self.初始种群)
        历代最优适应度 = []
        历代最优个体 = []
        历代全部种群 = []

        已评价种群 = []
        for 个体 in 种群:
            if self.工具.指标评估次数 >= 目标预算 and not self.工具.已缓存(个体):
                break
            已评价种群.append((个体, self.工具.适应度计算(个体, self.距离矩阵)))
        if not 已评价种群:
            raise RuntimeError("GA在评价初始种群前已耗尽预算")

        全局最优个体, 全局最优适应度 = min(已评价种群, key=lambda 项: 项[1])
        全局最优个体 = 全局最优个体[:]
        代数 = 0
        连续无新解代数 = 0
        # 在极少数随机种子下，交叉和变异可能长期只产生缓存中的重复解。
        # 5000代远高于论文实验的正常GA代数，仅作为病理性空转的确定性安全阀，
        # 不改变正常运行的搜索轨迹、评价预算或论文中的算法参数。
        安全代数上限 = max(5000, 最大代数 * 25)

        while self.工具.指标评估次数 < 目标预算:
            if not 按预算终止 and 代数 >= 最大代数:
                break

            排序种群 = sorted(已评价种群, key=lambda 项: 项[1])
            父代列表 = [
                个体 for 个体, _ in 排序种群[:min(父代数量, len(排序种群))]
            ]
            if len(父代列表) < 2:
                break

            新种群 = [
                个体[:] for 个体, _ in 排序种群[:min(精英数量, len(排序种群))]
            ]
            while len(新种群) + 1 < len(种群):
                父代1, 父代2 = random.sample(父代列表, 2)
                子代1, 子代2 = self.工具.OX交叉(父代1, 父代2, self.禁忌表)
                新种群.extend([子代1, 子代2])
            if len(新种群) < len(种群):
                父代1, 父代2 = random.sample(父代列表, 2)
                新种群.append(self.工具.OX交叉(父代1, 父代2, self.禁忌表)[0])

            for i in range(min(精英数量, len(新种群)), len(新种群)):
                新种群[i] = self._变异操作(新种群[i])

            评价前 = self.工具.指标评估次数
            下一代 = []
            for 个体 in 新种群:
                if self.工具.指标评估次数 >= 目标预算 and not self.工具.已缓存(个体):
                    continue
                适应度 = self.工具.适应度计算(个体, self.距离矩阵)
                下一代.append((个体, 适应度))

            if not 下一代:
                break
            已评价种群 = 下一代
            种群 = [个体 for 个体, _ in 已评价种群]
            本代最优个体, 本代最优适应度 = min(已评价种群, key=lambda 项: 项[1])
            if 本代最优适应度 < 全局最优适应度 - 1e-12:
                全局最优个体 = 本代最优个体[:]
                全局最优适应度 = 本代最优适应度

            历代最优个体.append(全局最优个体[:])
            历代最优适应度.append(全局最优适应度)
            if self.参数.get("记录全部种群", False):
                历代全部种群.append(copy.deepcopy(种群))

            if self.工具.指标评估次数 == 评价前:
                连续无新解代数 += 1
            else:
                连续无新解代数 = 0
            if 连续无新解代数 >= 20 and self.工具.指标评估次数 < 目标预算:
                # 极端重复时注入一个未见随机排列，防止缓存协议出现空转。
                for _ in range(100):
                    随机个体 = random.sample(range(1, self.客户数量 + 1), self.客户数量)
                    if not self.工具.已缓存(随机个体):
                        随机适应度 = self.工具.适应度计算(随机个体, self.距离矩阵)
                        已评价种群[-1] = (随机个体, 随机适应度)
                        种群[-1] = 随机个体
                        连续无新解代数 = 0
                        break

            if (
                按预算终止
                and 代数 >= 安全代数上限
                and self.工具.指标评估次数 < 目标预算
            ):
                # 单个随机解注入在病理性高重复状态下进展过慢。
                # 达到安全上限后，每代批量注入至多一个种群规模的未见排列，
                # 仍将每个排列计入同一完整评价预算，并保留当前种群中的较优个体。
                剩余预算 = 目标预算 - self.工具.指标评估次数
                保底数量 = min(len(种群), 剩余预算)
                保底个体 = []
                for _ in range(保底数量):
                    for _ in range(1000):
                        随机个体 = random.sample(
                            range(1, self.客户数量 + 1), self.客户数量
                        )
                        if not self.工具.已缓存(随机个体):
                            随机适应度 = self.工具.适应度计算(
                                随机个体, self.距离矩阵
                            )
                            保底个体.append((随机个体, 随机适应度))
                            break
                    else:
                        raise RuntimeError("GA安全注入未能生成未缓存排列")

                保留数量 = max(0, len(种群) - len(保底个体))
                已评价种群 = (
                    sorted(已评价种群, key=lambda 项: 项[1])[:保留数量]
                    + 保底个体
                )
                种群 = [个体 for 个体, _ in 已评价种群]
                注入最优个体, 注入最优适应度 = min(
                    保底个体, key=lambda 项: 项[1]
                )
                if 注入最优适应度 < 全局最优适应度 - 1e-12:
                    全局最优个体 = 注入最优个体[:]
                    全局最优适应度 = 注入最优适应度
                连续无新解代数 = 0

            代数 += 1
            if self.参数.get("输出逐代日志", False):
                print(
                    f"GA 第{代数:3d}代｜F={全局最优适应度:.6f} | "
                    f"unique={self.工具.指标评估次数}/{目标预算}"
                )

        if not 历代最优个体:
            历代最优个体.append(全局最优个体[:])
            历代最优适应度.append(全局最优适应度)
        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": 历代全部种群,
            "最终种群": copy.deepcopy(种群),
            "最终最优个体": 全局最优个体,
            "指标评估次数": self.工具.指标评估次数,
            "实际GA代数": 代数,
        }

    def 运行(self):
        """运行GA算法"""
        if self.参数.get("发布级评价协议", False):
            return self._运行发布级协议()
        种群 = copy.deepcopy(self.初始种群)
        历代最优适应度 = []
        历代最优个体 = []
        历代全部种群 = []

        for 代数 in range(self.参数["迭代次数"]):
            # 选择和交叉
            种群 = self._选择交叉(种群,
                                  self.参数["精英保留数量"],
                                  self.参数["父代选择数量"])

            # 变异
            # GA也保护同样数量的精英，保证与SVGA的比较协议一致。
            for i in range(self.参数["精英保留数量"], len(种群)):
                种群[i] = self._变异操作(种群[i])
            if self.参数.get("记录全部种群", False):
                历代全部种群.append(copy.deepcopy(种群))

            # 记录最优解
            最优个体 = self._获取最优个体(种群)
            历代最优个体.append(最优个体)

            最优适应度 = self.工具.适应度计算(最优个体, self.距离矩阵)
            历代最优适应度.append(最优适应度)

            指标 = self.工具.路径指标计算(最优个体, self.距离矩阵)
            if self.参数.get("输出逐代日志", True):
                print(f"GA 第{代数 + 1:3d}代｜适应度={最优适应度:10.2f} | "
                      f"路径长={指标[2]:6d}  路径均衡={指标[3]:9.2f}  "
                      f"负载均衡={指标[4]:9.2f}")

        return {
            "历代最优适应度": 历代最优适应度,
            "历代最优个体": 历代最优个体,
            "历代全部种群": 历代全部种群,
            "最终种群": copy.deepcopy(种群),
            "最终最优个体": self._获取最优个体(种群),
            "指标评估次数": self.工具.指标评估次数,
        }


class SA求解器:
    """模拟退火算法求解器"""

    def __init__(self, 参数配置, 点列表, 距离矩阵, 仓库坐标):
        self.参数 = 参数配置
        self.点列表 = 点列表
        self.距离矩阵 = 距离矩阵
        self.仓库坐标 = 仓库坐标
        self.工具 = 工具类(参数配置)

    def 运行(self, 初始解):
        """运行模拟退火算法"""
        当前解 = 初始解[:]
        最优解 = 初始解[:]
        当前适应度 = self.工具.适应度计算(当前解, self.距离矩阵)
        最优适应度 = 当前适应度

        温度 = self.参数["初始温度"]
        历代解 = []
        迭代次数 = 0

        while 温度 > self.参数["最低温度"]:
            for _ in range(self.参数["每温度迭代次数"]):
                # 生成邻域解
                i, j = random.sample(range(len(当前解)), 2)
                新解 = 当前解[:]
                新解[i], 新解[j] = 新解[j], 新解[i]

                新适应度 = self.工具.适应度计算(新解, self.距离矩阵)

                # Metropolis准则
                if (新适应度 < 当前适应度 or
                        random.random() < math.exp((当前适应度 - 新适应度) / 温度)):
                    当前解, 当前适应度 = 新解, 新适应度

                    if 新适应度 < 最优适应度:
                        最优解, 最优适应度 = 新解[:], 新适应度
                        迭代次数 += 1
                        历代解.append(新解)

                        if self.参数.get("输出逐代日志", True):
                            指标 = self.工具.路径指标计算(新解, self.距离矩阵)
                            print(f"SA 第{迭代次数}代 | 适应度={新适应度:10.2f} | "
                                  f"路径长={指标[2]:6d}  路径均衡={指标[3]:9.2f}  "
                                  f"负载均衡={指标[4]:9.2f}")

            温度 *= self.参数["温度衰减率"]

        return {
            "历代解": 历代解,
            "最终最优个体": 最优解,
            "指标评估次数": self.工具.指标评估次数,
        }
